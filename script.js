const grid = document.querySelector('#project-grid');
window.PORTFOLIO_PROJECTS.forEach(project => {
  const link = document.createElement('a');
  link.href = project.url;
  link.className = 'project-card event-card';
  link.setAttribute('aria-label', `View ${project.title}`);
  const image = document.createElement('div');
  image.className = 'project-image';
  const img = document.createElement('img');
  img.src = `images/${project.file}`;
  img.alt = `${project.title} — collection preview`;
  img.loading = 'lazy'; img.width = 1200; img.height = 900;
  const title = document.createElement('h3');
  title.className = 'event-card-title'; title.textContent = project.title;
  const arrow = document.createElement('span');
  arrow.className = 'open'; arrow.textContent = '↗'; arrow.setAttribute('aria-hidden', 'true');
  image.append(img, title, arrow);
  const meta = document.createElement('div'); meta.className = 'project-meta';
  const label = document.createElement('span'); label.className = 'collection-link-label'; label.textContent = 'View collection ↗';
  const count = document.createElement('p'); count.textContent = project.kind;
  meta.append(label, count); link.append(image, meta); grid.append(link);
});
document.querySelector('#filter-status').textContent = '4 design collections';
document.querySelector('#year').textContent = new Date().getFullYear();
